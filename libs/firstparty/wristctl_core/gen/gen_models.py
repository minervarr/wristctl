#!/usr/bin/env python3
"""Generate the model registry (Python and C) from spec/models.json."""

from __future__ import annotations

import argparse
from pathlib import Path

CORE = Path(__file__).resolve().parent.parent
WRISTCTL = CORE.parents[2]
DEFAULT_SPEC = CORE / "spec" / "models.json"
PY_OUT = WRISTCTL / "py" / "wristctl_proto" / "generated" / "models.py"
C_HEADER = CORE / "include" / "wristctl" / "models.h"
C_SOURCE = CORE / "src" / "models.c"


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate_py(spec: dict) -> str:
    flags = spec["flag_names"]
    models = spec["models"]
    lines = [
        "# Generated by gen/gen_models.py from spec/models.json. Do not edit.",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Model:",
        "    name: str",
        "    aliases: tuple[str, ...]",
        "    generation: int",
        "    service_size: int",
        "    flags: bytes",
        "",
        "",
        f"FLAG_NAMES: tuple[str, ...] = {flags!r}".replace("'", '"'),
        "",
        "MODELS: tuple[Model, ...] = (",
    ]
    for model in models:
        aliases = "(" + ", ".join(f'"{a}"' for a in model["aliases"]) + ("," if len(model["aliases"]) == 1 else "") + ")"
        lines.append(
            f'    Model("{model["name"]}", {aliases}, {model["generation"]}, '
            f'{model["service_size"]}, bytes.fromhex("{model["bits"]}")),'
        )
    lines += [
        ")",
        "",
        "",
        "def lookup(ble_name: str) -> Model | None:",
        '    """Match an advertised name the way the vendor app does: longest substring wins."""',
        "    if not ble_name:",
        "        return None",
        "    best: Model | None = None",
        "    best_len = 0",
        "    for model in MODELS:",
        "        for alias in model.aliases:",
        "            if alias and alias in ble_name and len(alias) > best_len:",
        "                best = model",
        "                best_len = len(alias)",
        "    return best",
        "",
        "",
        "def flag(model: Model, name: str) -> bool:",
        '    """Read one capability flag; raises KeyError for an unknown name."""',
        "    try:",
        "        index = FLAG_NAMES.index(name)",
        "    except ValueError:",
        "        raise KeyError(name) from None",
        "    return bool(model.flags[index // 8] & (1 << (index % 8)))",
        "",
    ]
    return "\n".join(lines)


def generate_c_header(spec: dict) -> str:
    flags = spec["flag_names"]
    width = (len(flags) + 7) // 8
    max_aliases = max(len(model["aliases"]) for model in spec["models"])
    lines = [
        "/* Generated by gen/gen_models.py from spec/models.json. Do not edit. */",
        "#ifndef WRISTCTL_MODELS_H",
        "#define WRISTCTL_MODELS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f"#define WC_FLAG_BYTES {width}",
        f"#define WC_MODEL_MAX_ALIASES {max_aliases}",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint8_t alias_count;",
        "    const char *aliases[WC_MODEL_MAX_ALIASES];",
        "    uint8_t generation;",
        "    int16_t service_size;",
        "    uint8_t flags[WC_FLAG_BYTES];",
        "} wc_model;",
        "",
        "extern const wc_model wc_models[];",
        "extern const size_t wc_model_count;",
        "extern const char *const wc_flag_names[];",
        "extern const size_t wc_flag_count;",
        "",
        "/* Longest substring match against the advertised name, as the vendor app does.",
        " * Returns NULL when no alias matches. */",
        "const wc_model *wc_model_lookup(const char *ble_name);",
        "",
        "/* 1 or 0, or -1 when the flag name is unknown. */",
        "int wc_model_flag(const wc_model *model, const char *flag_name);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* WRISTCTL_MODELS_H */",
        "",
    ]
    return "\n".join(lines)


def generate_c_source(spec: dict) -> str:
    flags = spec["flag_names"]
    models = spec["models"]
    lines = [
        "/* Generated by gen/gen_models.py from spec/models.json. Do not edit. */",
        '#include "wristctl/models.h"',
        "",
        "#include <string.h>",
        "",
        "const wc_model wc_models[] = {",
    ]
    for model in models:
        aliases = [c_string(alias) for alias in model["aliases"]]
        while len(aliases) < max(len(m["aliases"]) for m in models):
            aliases.append("NULL")
        bits = ", ".join(f"0x{b:02x}" for b in bytes.fromhex(model["bits"]))
        lines.append("    {")
        lines.append(f"        {c_string(model['name'])}, {len(model['aliases'])}, {{{', '.join(aliases)}}},")
        lines.append(f"        {model['generation']}, {model['service_size']}, {{{bits}}},")
        lines.append("    },")
    lines += [
        "};",
        "",
        "const size_t wc_model_count = sizeof wc_models / sizeof wc_models[0];",
        "",
        "const char *const wc_flag_names[] = {",
    ]
    for flag in flags:
        lines.append(f"    {c_string(flag)},")
    lines += [
        "};",
        "",
        "const size_t wc_flag_count = sizeof wc_flag_names / sizeof wc_flag_names[0];",
        "",
        "const wc_model *wc_model_lookup(const char *ble_name)",
        "{",
        "    if (ble_name == NULL) {",
        "        return NULL;",
        "    }",
        "    const wc_model *best = NULL;",
        "    size_t best_len = 0;",
        "    for (size_t i = 0; i < wc_model_count; i++) {",
        "        const wc_model *model = &wc_models[i];",
        "        for (size_t a = 0; a < model->alias_count; a++) {",
        "            const char *alias = model->aliases[a];",
        "            if (alias == NULL || alias[0] == '\\0') {",
        "                continue;",
        "            }",
        "            if (strstr(ble_name, alias) != NULL) {",
        "                size_t len = strlen(alias);",
        "                if (len > best_len) {",
        "                    best = model;",
        "                    best_len = len;",
        "                }",
        "            }",
        "        }",
        "    }",
        "    return best;",
        "}",
        "",
        "int wc_model_flag(const wc_model *model, const char *flag_name)",
        "{",
        "    if (model == NULL || flag_name == NULL) {",
        "        return -1;",
        "    }",
        "    for (size_t i = 0; i < wc_flag_count; i++) {",
        "        if (strcmp(wc_flag_names[i], flag_name) == 0) {",
        "            return (model->flags[i / 8] & (uint8_t)(1u << (i % 8))) ? 1 : 0;",
        "        }",
        "    }",
        "    return -1;",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    args = parser.parse_args(argv)
    import json

    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    C_HEADER.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.write_text(generate_py(spec), encoding="utf-8")
    C_HEADER.write_text(generate_c_header(spec), encoding="utf-8")
    C_SOURCE.write_text(generate_c_source(spec), encoding="utf-8")
    print(
        f"{len(spec['models'])} models, {len(spec['flag_names'])} flags "
        f"-> {PY_OUT.name}, {C_HEADER.name}, {C_SOURCE.name}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
