#!/usr/bin/env python3
"""Generate the C codecs and class metadata from spec/classes.json."""

from __future__ import annotations

import argparse
from pathlib import Path

import spec_lib

CORE = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = CORE / "spec" / "classes.json"
HEADER = CORE / "include" / "wristctl" / "generated.h"
SOURCE = CORE / "src" / "generated.c"


class Emitter:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def w(self, text: str = "") -> None:
        self.lines.append(text)

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def c_struct_name(cls: dict) -> str:
    return "wc_" + cls["name"]


def item_name(cls: dict, field: dict) -> str:
    return f"{c_struct_name(cls)}_{field['name']}_item"


def offset_of(fields: list[dict], name: str) -> int:
    for field in fields:
        if field["name"] == name:
            return field["offset"]
    raise KeyError(name)


def emit_header(spec: dict) -> str:
    e = Emitter()
    e.w("/* Generated by gen/gen_c.py from spec/classes.json. Do not edit. */")
    e.w("#ifndef WRISTCTL_GENERATED_H")
    e.w("#define WRISTCTL_GENERATED_H")
    e.w()
    e.w("#include <stddef.h>")
    e.w("#include <stdint.h>")
    e.w()
    e.w('#include "wristctl/proto.h"')
    e.w()
    e.w("#ifdef __cplusplus")
    e.w('extern "C" {')
    e.w("#endif")
    e.w()
    for cls in spec["classes"]:
        for field in cls["fields"]:
            if field["type"] != "array":
                continue
            e.w(f"typedef struct {item_name(cls, field)} {{")
            for sub in field["fields"]:
                if "expected" in sub:
                    continue
                if sub["type"] == "bit":
                    e.w(f"    uint8_t {sub['name']};")
                elif sub["type"] == "bytes":
                    e.w(f"    uint8_t {sub['name']}[{sub['length']}];")
                elif sub["type"] == "string":
                    e.w(f"    char {sub['name']}[{sub['length'] + 1}];")
                elif sub["type"] == "u16le":
                    e.w(f"    uint16_t {sub['name']};")
                elif sub["type"] == "i8":
                    e.w(f"    int8_t {sub['name']};")
                else:
                    e.w(f"    uint8_t {sub['name']};")
            e.w(f"}} {item_name(cls, field)};")
            e.w()
        e.w(f"typedef struct {c_struct_name(cls)} {{")
        emitted = False
        for field in cls["fields"]:
            if "expected" in field:
                continue
            if field["type"] == "array":
                e.w(f"    {item_name(cls, field)} {field['name']}[{field['count']}];")
            elif field["type"] == "bit":
                e.w(f"    uint8_t {field['name']};")
            elif field["type"] == "bytes":
                e.w(f"    uint8_t {field['name']}[{field['length']}];")
            elif field["type"] == "string":
                e.w(f"    char {field['name']}[{field['length'] + 1}];")
            elif field["type"] == "u16le":
                e.w(f"    uint16_t {field['name']};")
            elif field["type"] == "i8":
                e.w(f"    int8_t {field['name']};")
            else:
                e.w(f"    uint8_t {field['name']};")
            emitted = True
        if not emitted:
            e.w("    uint8_t unused;")
        e.w(f"}} {c_struct_name(cls)};")
        e.w(f"#define WC_LEN_{cls['name'].upper()} {cls['length']['max']}")
        e.w()
        e.w(
            f"int {c_struct_name(cls)}_decode(const uint8_t *in, size_t n, "
            f"{c_struct_name(cls)} *out);"
        )
        e.w(
            f"int {c_struct_name(cls)}_encode(const {c_struct_name(cls)} *v, "
            f"uint8_t *out, size_t cap, size_t *out_n);"
        )
        e.w()
    e.w("typedef struct {")
    e.w("    uint8_t id;")
    e.w("    uint8_t direction;")
    e.w("    uint8_t confidence;")
    e.w("    size_t length;")
    e.w("    const char *name;")
    e.w("    const char *title;")
    e.w("} wc_class_info;")
    e.w()
    e.w("const wc_class_info *wc_class_by_id(uint8_t id);")
    e.w("size_t wc_class_count(void);")
    e.w()
    e.w("#ifdef __cplusplus")
    e.w("}")
    e.w("#endif")
    e.w()
    e.w("#endif /* WRISTCTL_GENERATED_H */")
    return e.text()


def emit_decode_body(e: Emitter, cls: dict) -> None:
    name = c_struct_name(cls)
    total = cls["length"]["max"]
    e.w(f"int {name}_decode(const uint8_t *in, size_t n, {name} *out)")
    e.w("{")
    e.w("    if (in == NULL || out == NULL) {")
    e.w("        return WC_ERR_ARG;")
    e.w("    }")
    e.w(f"    if (n < {total}) {{")
    e.w("        return WC_ERR_SHORT;")
    e.w("    }")
    e.w(f"    if (in[0] != {cls['id']:#04x}) {{")
    e.w("        return WC_ERR_CLASS;")
    e.w("    }")
    for field in cls["fields"]:
        if "expected" in field:
            offset = field["offset"]
            e.w(f"    if (in[{offset}] != {field['expected']:#04x}) {{")
            e.w("        return WC_ERR_CONST;")
            e.w("    }")
    e.w("    memset(out, 0, sizeof *out);")
    emit_decode_scope(e, cls, cls["fields"], "in", "out->", 1)
    e.w("    return WC_OK;")
    e.w("}")
    e.w()


def emit_decode_scope(
    e: Emitter, cls: dict, fields: list[dict], base: str, prefix: str, level: int
) -> None:
    indent = "    " * level
    groups = spec_lib.bits_by_container(fields)
    for field in fields:
        if "expected" in field:
            continue
        name = field["name"]
        kind = field["type"]
        if kind == "bit":
            continue
        offset = field["offset"]
        src = f"{base}[{offset}]" if base else f"in[{offset}]"
        if kind == "u8":
            e.w(f"{indent}{prefix}{name} = {src};")
        elif kind == "i8":
            e.w(f"{indent}{prefix}{name} = (int8_t){src};")
        elif kind == "bcd8":
            e.w(f"{indent}{prefix}{name} = (uint8_t)((({src} >> 4) & 0x0F) * 10 + ({src} & 0x0F));")
        elif kind == "u16le":
            e.w(f"{indent}{prefix}{name} = (uint16_t)({src} | ((uint16_t){base}[{offset + 1}] << 8));")
        elif kind == "bytes":
            e.w(f"{indent}memcpy({prefix}{name}, {base} + {offset}, {field['length']});")
        elif kind == "string":
            length = field["length"]
            e.w(f"{indent}memcpy({prefix}{name}, {base} + {offset}, {length});")
            e.w(f"{indent}{prefix}{name}[{length}] = '\\0';")
        elif kind == "array":
            stride = field["stride"]
            e.w(f"{indent}for (size_t i = 0; i < {field['count']}; i++) {{")
            e.w(f"{indent}    const uint8_t *item = {base} + {offset} + {stride} * i;")
            e.w(f"{indent}    (void)item;")
            emit_decode_scope(e, cls, field["fields"], "item", f"{prefix}{name}[i].", level + 1)
            e.w(f"{indent}}}")
        else:  # pragma: no cover
            raise AssertionError(kind)
    for container, bits in groups.items():
        offset = offset_of(fields, container)
        src = f"{base}[{offset}]" if base else f"in[{offset}]"
        e.w(f"{indent}{prefix}{container} = {src};")
        for bit in bits:
            e.w(f"{indent}{prefix}{bit['name']} = (uint8_t)(({src} & {bit['mask']:#04x}) ? 1 : 0);")


def emit_encode_body(e: Emitter, cls: dict) -> None:
    name = c_struct_name(cls)
    total = cls["length"]["max"]
    e.w(
        f"int {name}_encode(const {name} *v, uint8_t *out, size_t cap, size_t *out_n)"
    )
    e.w("{")
    e.w("    if (v == NULL || out == NULL) {")
    e.w("        return WC_ERR_ARG;")
    e.w("    }")
    e.w(f"    if (cap < {total}) {{")
    e.w("        return WC_ERR_CAPACITY;")
    e.w("    }")
    e.w(f"    memset(out, 0, {total});")
    e.w(f"    out[0] = {cls['id']:#04x};")
    emit_encode_scope(e, cls, cls["fields"], "v->", "out", 1)
    e.w(f"    if (out_n != NULL) {{")
    e.w(f"        *out_n = {total};")
    e.w("    }")
    e.w("    return WC_OK;")
    e.w("}")
    e.w()



def emit_range_guard(
    e: Emitter, indent: str, expr: str, field: dict, type_min: int, type_max: int
) -> None:
    """Emit only the bounds that can actually fail for the field's C type."""
    if "range" not in field:
        return
    lo, hi = field["range"]
    checks = []
    if lo > type_min:
        checks.append(f"{expr} < {lo}")
    if hi < type_max:
        checks.append(f"{expr} > {hi}")
    if not checks:
        return
    e.w(f"{indent}if ({' || '.join(checks)}) {{")
    e.w("        return WC_ERR_RANGE;")
    e.w("    }")

def emit_encode_scope(
    e: Emitter, cls: dict, fields: list[dict], prefix: str, out: str, level: int
) -> None:
    indent = "    " * level
    groups = spec_lib.bits_by_container(fields)
    for field in fields:
        name = field["name"]
        if "expected" in field:
            e.w(f"{indent}{out}[{field['offset']}] = {field['expected']:#04x};")
            continue
        kind = field["type"]
        if kind == "bit":
            continue
        offset = field["offset"]
        if kind == "u8":
            if name in groups:
                continue
            emit_range_guard(e, indent, f"{prefix}{name}", field, 0, 0xFF)
            e.w(f"{indent}{out}[{offset}] = {prefix}{name};")
        elif kind == "i8":
            emit_range_guard(e, indent, f"{prefix}{name}", field, -128, 127)
            e.w(f"{indent}{out}[{offset}] = (uint8_t)({prefix}{name} & 0xFF);")
        elif kind == "bcd8":
            e.w(f"{indent}if ({prefix}{name} > 99) {{")
            e.w("        return WC_ERR_BCD;")
            e.w("    }")
            e.w(f"{indent}{out}[{offset}] = (uint8_t)((({prefix}{name} / 10) << 4) | ({prefix}{name} % 10));")
        elif kind == "u16le":
            emit_range_guard(e, indent, f"{prefix}{name}", field, 0, 0xFFFF)
            e.w(f"{indent}{out}[{offset}] = (uint8_t)({prefix}{name} & 0xFF);")
            e.w(f"{indent}{out}[{offset + 1}] = (uint8_t)(({prefix}{name} >> 8) & 0xFF);")
        elif kind == "bytes":
            e.w(f"{indent}memcpy({out} + {offset}, {prefix}{name}, {field['length']});")
        elif kind == "string":
            length = field["length"]
            e.w(f"{indent}if (strlen({prefix}{name}) > {length}) {{")
            e.w("        return WC_ERR_LENGTH;")
            e.w("    }")
            e.w(f"{indent}memcpy({out} + {offset}, {prefix}{name}, strlen({prefix}{name}));")
        elif kind == "array":
            stride = field["stride"]
            e.w(f"{indent}for (size_t i = 0; i < {field['count']}; i++) {{")
            e.w(f"{indent}    uint8_t *item = {out} + {offset} + {stride} * i;")
            e.w(f"{indent}    (void)item;")
            emit_encode_scope(e, cls, field["fields"], f"{prefix}{name}[i].", "item", level + 1)
            e.w(f"{indent}}}")
        else:  # pragma: no cover
            raise AssertionError(kind)
    for container, bits in groups.items():
        offset = offset_of(fields, container)
        var = f"flags_{container}"
        e.w(f"{indent}uint8_t {var} = (uint8_t)({prefix}{container} & 0xFF);")
        for bit in bits:
            mask = bit["mask"]
            inv = (~mask) & 0xFF
            e.w(
                f"{indent}{var} = {prefix}{bit['name']} ? (uint8_t)({var} | {mask:#04x}) "
                f": (uint8_t)({var} & {inv:#04x});"
            )
        e.w(f"{indent}{out}[{offset}] = {var};")


def emit_source(spec: dict) -> str:
    e = Emitter()
    e.w("/* Generated by gen/gen_c.py from spec/classes.json. Do not edit. */")
    e.w('#include "wristctl/generated.h"')
    e.w()
    e.w("#include <string.h>")
    e.w()
    for cls in spec["classes"]:
        emit_decode_body(e, cls)
        emit_encode_body(e, cls)
    e.w("static const wc_class_info class_info[] = {")
    for cls in spec["classes"]:
        direction = {"read": "WC_DIR_READ", "write": "WC_DIR_WRITE", "readwrite": "WC_DIR_READWRITE"}[
            cls["direction"]
        ]
        confidence = {
            "observed": "WC_CONFIDENCE_OBSERVED",
            "derived": "WC_CONFIDENCE_DERIVED",
            "inferred": "WC_CONFIDENCE_INFERRED",
        }[cls["confidence"]]
        e.w(
            f"    {{{cls['id']:#04x}, {direction}, {confidence}, {cls['length']['max']}, "
            f'"{cls["name"]}", "{cls["title"]}"}},'
        )
    e.w("};")
    e.w()
    e.w("const wc_class_info *wc_class_by_id(uint8_t id)")
    e.w("{")
    e.w("    for (size_t i = 0; i < sizeof class_info / sizeof class_info[0]; i++) {")
    e.w("        if (class_info[i].id == id) {")
    e.w("            return &class_info[i];")
    e.w("        }")
    e.w("    }")
    e.w("    return NULL;")
    e.w("}")
    e.w()
    e.w("size_t wc_class_count(void)")
    e.w("{")
    e.w("    return sizeof class_info / sizeof class_info[0];")
    e.w("}")
    return e.text()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    args = parser.parse_args(argv)
    spec = spec_lib.load(args.spec)
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    SOURCE.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(emit_header(spec), encoding="utf-8")
    SOURCE.write_text(emit_source(spec), encoding="utf-8")
    print(f"wrote {HEADER} and {SOURCE} ({len(spec['classes'])} classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
