#!/usr/bin/env python3
"""Generate the C vector test from spec/vectors/*.json.

The C test is dependency-free: JSON is consumed here, never at run time. Each
vector produces two checks, decode and encode, so a codec cannot pass by being
self-consistently wrong in one direction.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import spec_lib

CORE = Path(__file__).resolve().parent.parent
SPEC = CORE / "spec" / "classes.json"
VECTORS = CORE / "spec" / "vectors"
OUT = CORE / "tests" / "generated_vectors.h"


def c_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def c_bytes(hexstr: str) -> str:
    raw = bytes.fromhex(hexstr)
    return "(const uint8_t[]){" + ", ".join(f"0x{b:02x}" for b in raw) + "}"


def c_ident(index: int) -> str:
    return f"{index:02d}"


def emit_field_checks(e, field: dict, path: str, expected, vector_id: str, indent: str) -> None:
    kind = field["type"]
    name = field["name"]
    if "expected" in field:
        return
    target = f"{path}.{name}"
    if kind == "array":
        for index, item in enumerate(expected):
            for sub in field["fields"]:
                if "expected" in sub:
                    continue
                emit_field_checks(e, sub, f"{target}[{index}]", item[sub["name"]], vector_id, indent)
        return
    if kind == "bit":
        want = 1 if expected else 0
        e.append(f'{indent}VEC_CHECK({target} == {want}, "{vector_id}", "{name}");')
        return
    if kind == "bytes":
        e.append(
            f"{indent}VEC_CHECK(memcmp({target}, {c_bytes(expected)}, {field['length']}) == 0, "
            f'"{vector_id}", "{name}");'
        )
        return
    if kind == "string":
        e.append(f'{indent}VEC_CHECK(strcmp({target}, {c_string(expected)}) == 0, "{vector_id}", "{name}");')
        return
    e.append(f'{indent}VEC_CHECK({target} == {expected}, "{vector_id}", "{name}");')


def emit_field_sets(e, field: dict, path: str, value, indent: str) -> None:
    kind = field["type"]
    name = field["name"]
    if "expected" in field:
        return
    target = f"{path}.{name}"
    if kind == "array":
        for index, item in enumerate(value):
            for sub in field["fields"]:
                if "expected" in sub:
                    continue
                emit_field_sets(e, sub, f"{target}[{index}]", item[sub["name"]], indent)
        return
    if kind == "bytes":
        e.append(f"{indent}memcpy({target}, {c_bytes(value)}, {field['length']});")
        return
    if kind == "string":
        e.append(f"{indent}strcpy({target}, {c_string(value)});")
        return
    if kind == "bit":
        e.append(f"{indent}{target} = {1 if value else 0};")
        return
    e.append(f"{indent}{target} = {value};")


def generate(spec: dict, vectors: list[dict]) -> str:
    classes = {cls["name"]: cls for cls in spec["classes"]}
    e: list[str] = []
    e.append("/* Generated by gen/gen_vectors.py from spec/classes.json and spec/vectors. */")
    e.append("#ifndef WRISTCTL_TEST_VECTORS_H")
    e.append("#define WRISTCTL_TEST_VECTORS_H")
    e.append("")
    e.append("#include <stdio.h>")
    e.append("#include <string.h>")
    e.append("")
    e.append('#include "wristctl/generated.h"')
    e.append("")
    e.append("#define VEC_CHECK(cond, id, what) do { \\")
    e.append('    if (!(cond)) { printf("FAIL %s: %s\\n", id, what); return 1; } \\')
    e.append("} while (0)")
    e.append("")

    entries: list[tuple[str, str]] = []
    for index, vector in enumerate(vectors, start=1):
        cls = classes[vector["class"]]
        cname = "wc_" + cls["name"]
        raw = bytes.fromhex(vector["bytes"])
        ident = c_ident(index)
        vid = vector["id"]
        e.append(f"/* {vid}: {vector['source']} */")
        e.append(
            f"static const uint8_t vec_{ident}_bytes[] = {{"
            + ", ".join(f"0x{b:02x}" for b in raw)
            + "};"
        )
        e.append("")
        e.append(f"static int vec_{ident}_decode(void)")
        e.append("{")
        e.append(f"    {cname} v;")
        e.append(f"    int rc = {cname}_decode(vec_{ident}_bytes, sizeof vec_{ident}_bytes, &v);")
        e.append(f'    VEC_CHECK(rc == WC_OK, "{vid}", "decode");')
        for field in cls["fields"]:
            emit_field_checks(e, field, "v", vector["decoded"][field["name"]] if field["name"] in vector["decoded"] else None, vid, "    ")
        e.append("    return 0;")
        e.append("}")
        e.append("")
        e.append(f"static int vec_{ident}_encode(void)")
        e.append("{")
        e.append(f"    {cname} v;")
        e.append("    memset(&v, 0, sizeof v);")
        for field in cls["fields"]:
            if field["name"] in vector["decoded"]:
                emit_field_sets(e, field, "v", vector["decoded"][field["name"]], "    ")
        e.append("    uint8_t out[256];")
        e.append("    size_t n = 0;")
        e.append(f"    int rc = {cname}_encode(&v, out, sizeof out, &n);")
        e.append(f'    VEC_CHECK(rc == WC_OK, "{vid}", "encode");')
        e.append(f'    VEC_CHECK(n == sizeof vec_{ident}_bytes, "{vid}", "encoded length");')
        e.append(
            f'    VEC_CHECK(memcmp(out, vec_{ident}_bytes, n) == 0, "{vid}", "encoded bytes");'
        )
        e.append("    return 0;")
        e.append("}")
        e.append("")
        entries.append((f"{vid}/decode", f"vec_{ident}_decode"))
        entries.append((f"{vid}/encode", f"vec_{ident}_encode"))

    e.append("typedef struct {")
    e.append("    const char *name;")
    e.append("    int (*fn)(void);")
    e.append("} vec_entry;")
    e.append("")
    e.append("static const vec_entry vec_entries[] = {")
    for name, fn in entries:
        e.append(f'    {{"{name}", {fn}}},')
    e.append("};")
    e.append("")
    e.append("static const size_t vec_entry_count = sizeof vec_entries / sizeof vec_entries[0];")
    e.append("")
    e.append("#endif /* WRISTCTL_TEST_VECTORS_H */")
    return "\n".join(e) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=SPEC)
    parser.add_argument("--vectors", type=Path, default=VECTORS)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    spec = spec_lib.load(args.spec)
    vectors = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(args.vectors.glob("*.json"))]
    classes = {cls["name"] for cls in spec["classes"]}
    for vector in vectors:
        if vector["class"] not in classes:
            raise SystemExit(f"{vector['id']}: unknown class {vector['class']}")
        if len(bytes.fromhex(vector["bytes"])) != next(
            cls["length"]["max"] for cls in spec["classes"] if cls["name"] == vector["class"]
        ):
            raise SystemExit(f"{vector['id']}: length does not match the spec")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generate(spec, vectors), encoding="utf-8")
    print(f"wrote {args.out} ({len(vectors)} vectors, {len(vectors) * 2} checks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
